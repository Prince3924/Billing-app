export const TRANSLATIONS = buildCombinedTranslations();

function buildCombinedTranslations() {
  const combined = {};
  const keys = Object.keys(en);
  for (let i = 0; i < keys.length; i += 1) {
    const k = keys[i];
    combined[k] = {
      english: en[k],
      hindi: hi[k] || en[k],
      hinglish: hing[k] || en[k],
    };
  }
  return combined;
}

export function normalizeLang(lang) {
  if (!lang) return 'hinglish';
  const raw = String(lang).toLowerCase().trim();
  if (raw === 'en' || raw === 'english') return 'english';
  if (raw === 'hi' || raw === 'hindi') return 'hindi';
  if (raw === 'hing' || raw === 'hinglish') return 'hinglish';
  return 'hinglish';
}

export function getTranslation(key, lang) {
  const norm = normalizeLang(lang);
  const dict = norm === 'english' ? en : norm === 'hindi' ? hi : hing;
  return dict[key] || en[key] || key;
}

export function t(key, lang, vars) {
  let str = getTranslation(key, lang);
  if (vars && typeof vars === 'object') {
    const varKeys = Object.keys(vars);
    for (let i = 0; i < varKeys.length; i += 1) {
      const vk = varKeys[i];
      str = str.split(`{${vk}}`).join(String(vars[vk] ?? ''));
    }
  }
  return str;
}
